/* ============================================================
   TOBI THE RAINCOAT CAT
   A side-scrolling platform game in a single file. Plain
   JavaScript drawing on an HTML canvas: no libraries, and no
   image or sound files (the art and music are made by the code).

   The script below is in eight parts, in this order:
     1. SIMULATION   the rules: movement, collisions, creatures, items, camera
     2. LEVELS       the four stages, written as short building steps
     3. PIXEL ART    the hero, creatures and items, drawn as grids of letters
     4. TILES, SCENERY AND BACKDROPS   painted by code, in four colour schemes
     5. LETTERS      the 5x7 pixel alphabet
     6. DRAWING      putting the scene on the screen
     7. SOUND        effects and music made from simple waves
     8. THE GAME     controls, screens, saving, and the main loop

   Good places to tinker:
     PH (part 1)     how the hero runs and jumps
     LEVELS (part 2) the layout of every stage
     PAL and the letter grids (part 3)   colours and sprites
     SONGS (part 7)  the tunes
   ============================================================ */
