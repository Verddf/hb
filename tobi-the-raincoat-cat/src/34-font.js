const GLYPH_ORDER = Object.keys(GLYPHS);
const GLYPH_X = {};
GLYPH_ORDER.forEach(function (ch, i) { GLYPH_X[ch] = i * 6; });
const FONT_ATLAS = {};   // colour -> image holding every letter in that colour

function fontAtlas(col) {
  if (FONT_ATLAS[col]) return FONT_ATLAS[col];
  const c = mk(GLYPH_ORDER.length * 6, 7), g = c.getContext('2d');
  g.fillStyle = col;
  GLYPH_ORDER.forEach(function (ch, i) {
    const r = GLYPHS[ch].split('/');
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (r[y][x] === '#') g.fillRect(i * 6 + x, y, 1, 1);
  });
  FONT_ATLAS[col] = c;
  return c;
}
function textW(str, sc) { return (str.length * 6 - 1) * (sc || 1); }
